const isObject = (v) => v && typeof v === 'object' && !Array.isArray(v);

export function mergeWithDefaults(defaults, current) {
  if (!isObject(defaults)) return current ?? defaults;
  const out = { ...(isObject(current) ? current : {}) };
  for (const key of Object.keys(defaults)) {
    const dv = defaults[key];
    const cv = out[key];
    if (isObject(dv)) {
      out[key] = mergeWithDefaults(dv, isObject(cv) ? cv : {});
    } else if (cv === undefined) {
      out[key] = dv;
    }
  }
  return out;
}
